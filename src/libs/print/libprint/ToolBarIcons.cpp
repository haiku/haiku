struct IconData {
	const uint8*	data;
	size_t			size;
	BBitmap*		bitmap;
};


static IconData kIcons[] = {
	{ kGoFirst, sizeof(kGoFirst), NULL },
	{ kGoFastBackward, sizeof(kGoFastBackward), NULL },
	{ kGoPrevious, sizeof(kGoPrevious), NULL },
	{ kGoNext, sizeof(kGoNext), NULL },
	{ kGoFastForward, sizeof(kGoFastForward), NULL },
	{ kGoLast, sizeof(kGoLast), NULL },
	{ kZoomIn, sizeof(kZoomIn), NULL },
	{ kZoomOut, sizeof(kZoomOut), NULL },
};


status_t
init_tool_bar_icons()
{
	const BSize toolBarIconsSize = be_control_look->ComposeIconSize(24);
	const BSize iconRenderSize = be_control_look->ComposeIconSize(24);

	BBitmap bitmap
		= BBitmap(BRect(BPoint(0, 0), iconRenderSize), B_BITMAP_NO_SERVER_LINK, B_RGBA32);

	for (uint32 i = 0; i < sizeof(kIcons) / sizeof(IconData); i++) {
		status_t ret = BIconUtils::GetVectorIcon(kIcons[i].data, kIcons[i].size, &bitmap);
		if (ret != B_OK)
			return ret;

		kIcons[i].bitmap
			= new(std::nothrow) BBitmap(BRect(BPoint(0, 0), toolBarIconsSize), 0, B_RGBA32);

		if (kIcons[i].bitmap == NULL)
			return B_NO_MEMORY;

		ret = kIcons[i].bitmap->InitCheck();
		if (ret != B_OK)
			return ret;

		kIcons[i].bitmap->ImportBits(&bitmap, BPoint(0, 0), BPoint(0, 0), toolBarIconsSize);
	}

	return B_OK;
}


void
uninit_tool_bar_icons()
{
	for (uint32 i = 0; i < sizeof(kIcons) / sizeof(IconData); i++) {
		delete kIcons[i].bitmap;
		kIcons[i].bitmap = NULL;
	}
}


const BBitmap*
tool_bar_icon(uint32 which)
{
	if (which >= sizeof(kIcons) / sizeof(IconData))
		return NULL;

	return kIcons[which].bitmap;
}
